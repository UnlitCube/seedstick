#!/usr/bin/env node
// 配布物に入る第三者ソフトウェアの通知文 (THIRD_PARTY_NOTICES.txt) を作る。
//
//   node scripts/gen-third-party-notices.mjs          # 書き出す
//   node scripts/gen-third-party-notices.mjs --check  # コミット済みのものと一致するか（CI）
//
// **依存を増やさない。** license-checker 等は使わず、apps/desktop の package.json から
// `dependencies` を自分で辿る。`npm ls -w` はワークスペースの子（shared → yaml）を
// 辿りきらず、実際に配っている yaml が一覧から漏れた（実測）。
//
// 本番依存にコピーレフト（GPL / AGPL / LGPL / SSPL）や不明なライセンスが入ったら止める。
// 配布物に入る LGPL のバイナリ（7-Zip・NSIS プラグイン）は npm の依存ではないので、
// 下の FIXED に**理由つきで**手で載せる。
//
// 出力は apps/desktop/build/THIRD_PARTY_NOTICES.txt。electron-builder の
// extraResources が本体とインストーラの resources/ に入れる。

import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const APP = join(ROOT, 'apps', 'desktop')
const OUT = join(APP, 'build', 'THIRD_PARTY_NOTICES.txt')
const LICENSES = join(APP, 'build', 'licenses')

/**
 * 本番依存に**許す**ライセンス（許可リスト）。ここに無いものは止める。
 * 禁止リストにしていたときは MPL / EPL / CDDL / CC-BY-SA や `SEE LICENSE IN …` が素通りしていた。
 * SPDX の式は `A OR B` なら 1 つでも許せばよく、`A AND B` なら全部が要る。
 */
const PERMISSIVE = new Set(['MIT', 'ISC', 'BSD-2-Clause', 'BSD-3-Clause', 'Apache-2.0', '0BSD', 'CC0-1.0', 'BlueOak-1.0.0'])

function isPermissive(expr) {
  const e = String(expr).trim().replace(/^\((.*)\)$/, '$1')
  if (/\sOR\s/.test(e)) return e.split(/\s+OR\s+/).some(isPermissive)
  if (/\sAND\s/.test(e)) return e.split(/\s+AND\s+/).every(isPermissive)
  return PERMISSIVE.has(e)
}

/**
 * devDependency だが、**コードが配布物（renderer の束・CSS）に入る**もの。
 * vite は modulepreload の polyfill を、tailwindcss は preflight の CSS を出力に埋め込む。
 */
const BUNDLED_DEV = ['vite', 'tailwindcss']

/** パッケージのディレクトリを、それを要求した側のディレクトリから解決する。 */
function resolvePackageDir(name, fromDir) {
  let dir = fromDir
  for (;;) {
    const candidate = join(dir, 'node_modules', name, 'package.json')
    if (existsSync(candidate)) return dirname(candidate)
    const parent = dirname(dir)
    if (parent === dir) return null
    dir = parent
  }
}

function readJson(path) {
  return JSON.parse(readFileSync(path, 'utf8'))
}

function licenseText(dir) {
  const files = readdirSync(dir).filter((f) => /^(licen[cs]e|copying|notice)(\.|-|$)/i.test(f)).sort()
  return files.map((f) => readFileSync(join(dir, f), 'utf8').replace(/\r\n/g, '\n').trim()).join('\n\n')
}

/** 本番依存を辿って集める。ワークスペースのパッケージ（@autoinstall/*）は自分自身なので入れない。 */
function collect() {
  const found = new Map()
  const queue = [{ dir: APP, pkg: readJson(join(APP, 'package.json')), self: true }]
  while (queue.length > 0) {
    const { dir, pkg, self } = queue.shift()
    if (!self && !pkg.name.startsWith('@autoinstall/')) {
      const id = `${pkg.name}@${pkg.version}`
      if (found.has(id)) continue
      found.set(id, { name: pkg.name, version: pkg.version, license: licenseOf(pkg), dir, homepage: homepageOf(pkg) })
    }
    const deps = { ...(pkg.dependencies ?? {}), ...(pkg.optionalDependencies ?? {}) }
    for (const name of Object.keys(deps).sort()) {
      const d = resolvePackageDir(name, dir)
      if (d === null) {
        if (pkg.optionalDependencies?.[name]) continue
        throw new Error(`${pkg.name} の依存 ${name} が node_modules に見つからない（npm ci を先に）`)
      }
      queue.push({ dir: d, pkg: readJson(join(d, 'package.json')), self: false })
    }
  }
  for (const name of BUNDLED_DEV) {
    const d = resolvePackageDir(name, APP)
    if (d === null) throw new Error(`${name} が見つからない`)
    const pkg = readJson(join(d, 'package.json'))
    found.set(`${pkg.name}@${pkg.version}`, {
      name: pkg.name,
      version: pkg.version,
      license: licenseOf(pkg),
      dir: d,
      homepage: homepageOf(pkg),
      note: 'build tool; part of its code is embedded in the bundled output',
    })
  }
  return [...found.values()].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version))
}

function licenseOf(pkg) {
  if (typeof pkg.license === 'string') return pkg.license
  if (pkg.license && typeof pkg.license.type === 'string') return pkg.license.type
  return 'UNKNOWN'
}

function homepageOf(pkg) {
  const repo = typeof pkg.repository === 'string' ? pkg.repository : pkg.repository?.url
  return (pkg.homepage ?? repo ?? '').replace(/^git\+/, '').replace(/\.git$/, '')
}

function fixedFile(name) {
  return readFileSync(join(LICENSES, name), 'utf8').replace(/\r\n/g, '\n').trim()
}

