const packages = collect()
const bad = packages.filter((p) => !isPermissive(p.license))
if (bad.length > 0) {
  console.error('本番依存に、許可リストに無いライセンスがある（配布物の扱いを決めてから PERMISSIVE に足すこと）:')
  for (const p of bad) console.error(`  ${p.name}@${p.version}: ${p.license}`)
  process.exit(1)
}
const text = render(packages)

if (process.argv.includes('--check')) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : ''
  if (current !== text) {
    console.error(`${OUT} が古い。node scripts/gen-third-party-notices.mjs を実行してコミットすること。`)
    process.exit(1)
  }
  console.log(`ok: ${packages.length} packages, ${OUT} is up to date`)
} else {
  writeFileSync(OUT, text, 'utf8')
  console.log(`wrote ${OUT} (${packages.length} packages)`)
  for (const p of packages) console.log(`  ${p.name}@${p.version}  ${p.license}`)
}

